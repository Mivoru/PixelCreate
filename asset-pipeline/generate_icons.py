def rgba(hex_color):
    return tuple(int(hex_color[i:i + 2], 16) for i in (0, 2, 4)) + (255,)


def paint(shape, ramp):
    rows = [row for row in SHAPES[shape].strip("\n").split("\n")]
    image = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows[:16]):
        for x, char in enumerate(row[:16]):
            if char in "1234":
                image.putpixel((x, y), rgba(RAMPS[ramp][int(char) - 1]))
            elif char in ACCENTS:
                image.putpixel((x, y), rgba(ACCENTS[char]))

    # One pixel of outline around the silhouette, with the four neighbours only, so corners stay soft.
    outlined = image.copy()
    for y in range(16):
        for x in range(16):
            if image.getpixel((x, y))[3]:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < 16 and 0 <= ny < 16 and image.getpixel((nx, ny))[3]:
                    outlined.putpixel((x, y), rgba(OUTLINE))
                    break
    return outlined


def main():
    items = json.loads((ROOT / "world" / "items.json").read_text(encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    painted = []
    for item in items:
        shape, ramp = ICONS[item["icon"]]
        image = paint(shape, ramp)
        image.save(OUT / f"{item['icon']}.png")
        painted.append((item["icon"], image))

    if "--sheet" in sys.argv:
        columns = 8
        rows = (len(painted) + columns - 1) // columns
        sheet = Image.new("RGBA", (columns * 72, rows * 72), (40, 44, 60, 255))
        for i, (_, image) in enumerate(painted):
            sheet.paste(image.resize((64, 64), Image.NEAREST), ((i % columns) * 72 + 4, (i // columns) * 72 + 4), image.resize((64, 64), Image.NEAREST))
        target = ROOT / "export" / "previews" / "icons.png"
        target.parent.mkdir(parents=True, exist_ok=True)
        sheet.save(target)
        print(f"sheet: {target}")
    print(f"{len(painted)} icons in {OUT}")


if __name__ == "__main__":
    main()
